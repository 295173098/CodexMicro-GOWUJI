"""Build a separate HQ2116 routing review candidate; never export production Gerbers.

Run with KiCad's pcbnew module. Factory stackup/foil confirmation is still required.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

import pcbnew as k

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'hardware/rev-b'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    out = args.out.resolve()
    if out.exists():
        raise FileExistsError('Use a new output directory; do not mix review candidates')
    shutil.copytree(SOURCE, out)
    path = out / 'Gowuji-RevB.kicad_pcb'
    board = k.LoadBoard(str(path))
    changes = {}
    for track in board.GetTracks():
        if isinstance(track, k.PCB_VIA):
            continue
        net, width = track.GetNetname(), k.ToMM(track.GetWidth())
        target = None
        if net in ('/USB_P', '/USB_N') and width == .18:
            target = .22
        elif net in ('/RF_CHIP', '/RF_FEED') and width == .16:
            # Keep the short QFN pad escape narrow: widening violates pad clearance.
            if max(track.GetStart().x, track.GetEnd().x) < k.FromMM(45):
                target = .21
        if target:
            track.SetWidth(k.FromMM(target))
            changes[net] = changes.get(net, 0) + 1
    if changes != {'/USB_P': 6, '/USB_N': 10, '/RF_CHIP': 2, '/RF_FEED': 4}:
        raise ValueError(f'Source routing changed; re-review selection: {changes}')
    board.GetTitleBlock().SetRevision('B-HQ2116 REVIEW ONLY')
    k.ZONE_FILLER(board).Fill(board.Zones())
    k.SaveBoard(str(path), board)
    text = path.read_text()
    for old, new, expected in [
        ('(thickness 0.0994)', '(thickness 0.125)', 2),
        ('(material "3313")', '(material "2116")', 2),
        ('(epsilon_r 4.1)', '(epsilon_r 4.2)', 2),
        ('(thickness 1.265)', '(thickness 1.165)', 1),
        ('(material "NP-155F")', '(material "HQ core - confirm")', 1),
        ('(epsilon_r 4.5)', '(epsilon_r 4.2)', 1),
        ('(thickness 0.0152)', '(thickness 0.0175)', 4),
    ]:
        if text.count(old) != expected:
            raise ValueError(f'Unexpected stackup: {old}')
        # Only the two inner copper layers change; mask thickness stays 0.0152.
        if old == '(thickness 0.0152)':
            import re
            text, count = re.subn(r'(\(layer "In[12]\.Cu"\s+\(type "copper"\)\s+)\(thickness 0.0152\)',
                                  r'\g<1>(thickness 0.0175)', text)
            if count != 2:
                raise ValueError('Inner copper stackup not found')
        else:
            text = text.replace(old, new)
    path.write_text(text)
    manifest = {
        'status': 'routing_review_only_not_for_manufacture',
        'source_board_sha256': hashlib.sha256((SOURCE / path.name).read_bytes()).hexdigest(),
        'candidate_board_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        'changed_tracks': changes,
        'stackup': 'HQ04161H01-2116; public PP 0.125 mm; nominal 1.6 mm',
        'assumptions': ['finished outer copper 35 um, inner 17.5 um',
                        '1.2 mm copper-inclusive core -> dielectric 1.165 mm',
                        'public foil table is ambiguous; factory must confirm finished copper',
                        'listed layer thickness sum differs from nominal; factory must confirm'],
    }
    (out / 'cost-candidate.json').write_text(json.dumps(manifest, indent=2) + '\n')
    (out / 'READ-FIRST.txt').write_text(
        'REVIEW ONLY - DO NOT MANUFACTURE\n'
        'HQ2116 cost candidate; original production package is unchanged.\n'
        'Confirm actual stackup, finished foil, impedance and QFN via process.\n'
        'No Gerber/PCBA production package is generated by this script.\n')
    print(json.dumps(manifest, indent=2))


if __name__ == '__main__':
    main()
